document.addEventListener('DOMContentLoaded', () => {
    window.setLanguage = (language) => {
        document.querySelectorAll('[data-translate]').forEach(element => {
            const key = element.getAttribute('data-translate');
            if (translations[language] && translations[language][key]) {
                element.textContent = translations[language][key];
            }
        });
        
        // Handle placeholder translations
        document.querySelectorAll('[data-translate-placeholder]').forEach(element => {
            const key = element.getAttribute('data-translate-placeholder');
            if (translations[language] && translations[language][key]) {
                element.placeholder = translations[language][key];
            }
        });
        document.documentElement.lang = language;

        // Update language selector
        const langSelector = document.querySelector('.nav-language select');
        if (langSelector) {
            langSelector.value = language;
        }
    };

    window.getLanguage = () => {
        return localStorage.getItem('ramzLanguage') || 'en';
    };
    
    window.setStoredLanguage = (language) => {
        localStorage.setItem('ramzLanguage', language);
        setLanguage(language);
    };

    window.translate = (key) => {
        const lang = getLanguage();
        return translations[lang]?.[key] || key;
    };

    const lang = getLanguage();

    setLanguage(lang);
});
